# Pin Placement and Placement Blockages

## Pin Placement

Pin placement determines where input and output pins are positioned around the chip.

---

# Important Factors

- Connectivity
- Timing
- Routing distance
- Congestion
- Power requirements

---

# Good Pin Placement

Good pin placement can:

- Reduce wire length
- Reduce congestion
- Improve timing
- Simplify routing

---

# Placement Blockages

Placement blockages prevent standard cells from being placed in specific regions.

---

# Blockages May Be Used Around

- Macros
- Power structures
- Reserved regions
- Critical areas

---

## Key Learning

Proper pin placement and placement blockages help guide the physical design toward a routable implementation.
